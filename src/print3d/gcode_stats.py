"""What a PrusaSlicer G-code file says about itself: time, grams per tool, layers, thumbnails."""

from __future__ import annotations

import base64
import re
from dataclasses import dataclass

TIME_RE = re.compile(r"^; estimated printing time \(normal mode\) = (.+?)\s*$", re.MULTILINE)
GRAMS_RE = re.compile(r"^; filament used \[g\] = (.+?)\s*$", re.MULTILINE)
TOTAL_G_RE = re.compile(r"^; total filament used \[g\] = ([0-9.]+)", re.MULTILINE)
THUMB_RE = re.compile(
    r"^; thumbnail begin (\d+)x(\d+) \d+\n((?:; [^\n]*\n)+?); thumbnail end", re.MULTILINE
)


@dataclass(frozen=True)
class GcodeStats:
    estimated_time: str | None
    estimated_minutes: float | None
    filament_g: float | None
    grams_by_tool: dict[int, float]
    layer_count: int
    thumbnail_png: bytes | None


def is_prusaslicer(gcode: str) -> bool:
    return gcode.startswith("; generated by PrusaSlicer") or "\n; generated by PrusaSlicer" in gcode[:400]


def minutes(estimate: str | None) -> float | None:
    """'1d 2h 31m 12s' -> minutes."""
    if not estimate:
        return None
    unit_min = {"d": 1440.0, "h": 60.0, "m": 1.0, "s": 1 / 60.0}
    total = sum(float(v) * unit_min[u] for v, u in re.findall(r"(\d+(?:\.\d+)?)\s*([dhms])", estimate))
    return round(total, 1) if total else None


def _largest_thumbnail(gcode: str) -> bytes | None:
    best: tuple[int, bytes] | None = None
    for match in THUMB_RE.finditer(gcode):
        area = int(match.group(1)) * int(match.group(2))
        if best is None or area > best[0]:
            payload = "".join(line[2:].strip() for line in match.group(3).splitlines())
            try:
                best = (area, base64.b64decode(payload))
            except ValueError:
                continue
    return best[1] if best else None


def parse_prusaslicer(gcode: str) -> GcodeStats:
    time = TIME_RE.search(gcode)
    grams = GRAMS_RE.search(gcode)
    by_tool = (
        {i: float(v) for i, v in enumerate(grams.group(1).split(","), start=1)} if grams else {}
    )
    total = TOTAL_G_RE.search(gcode)
    return GcodeStats(
        estimated_time=time.group(1) if time else None,
        estimated_minutes=minutes(time.group(1)) if time else None,
        filament_g=float(total.group(1)) if total else (round(sum(by_tool.values()), 2) if by_tool else None),
        grams_by_tool=by_tool,
        layer_count=gcode.count("\n;LAYER_CHANGE"),
        thumbnail_png=_largest_thumbnail(gcode),
    )
